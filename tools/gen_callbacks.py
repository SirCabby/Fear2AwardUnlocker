#!/usr/bin/env python3
"""Generate src/callbacks_table.h - the ActionScript -> C++ callback table.

F.E.A.R. 2's menu reaches C++ through a table of 12-byte
{const char* name, void* handler, u8 flag} rows, filled in by a long run of
`movl $imm, <slot>` instructions in gameclient.dll. This scrapes those
instructions so the mod can hook every callback and see which ones the game
actually uses.

Usage: python3 tools/gen_callbacks.py --game-dir <FEAR2 dir> [--out src/callbacks_table.h]
"""

import argparse
import os
import re
import struct
import sys

PREFIXES = ("Menu.", "Global.", "Options.", "System.", "SaveGame.", "KeyBindings.",
            "Multiplayer.", "Performance.", "OnlineLogin.")
IMAGE_BASE = 0x10000000


def sections(d):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    out = []
    for i in range(nsec):
        o = pe + 24 + opt + i * 40
        vsz, vaddr, rsz, roff = struct.unpack_from("<IIII", d, o + 8)
        out.append((vaddr, vsz, roff, rsz))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--game-dir", required=True)
    ap.add_argument("--out", default="src/callbacks_table.h")
    args = ap.parse_args()

    path = os.path.join(args.game_dir, "Game", "gameclient.dll")
    with open(path, "rb") as fh:
        d = fh.read()
    secs = sections(d)

    def v2f(va):
        r = va - IMAGE_BASE
        for vaddr, vsz, roff, rsz in secs:
            if vaddr <= r < vaddr + vsz:
                return roff + (r - vaddr)
        return None

    def cstr(va):
        o = v2f(va)
        if o is None:
            return None
        try:
            e = d.index(b"\0", o)
        except ValueError:
            return None
        s = d[o:e]
        if not s or len(s) > 60 or not all(32 <= c < 127 for c in s):
            return None
        return s.decode()

    text_vaddr, text_vsz, text_off, text_sz = secs[0]

    # movl $imm32, <abs32>  ==  C7 05 <dst> <imm>
    writes = {}
    for off in range(text_off, text_off + text_sz - 10):
        if d[off] != 0xC7 or d[off + 1] != 0x05:
            continue
        dst = struct.unpack_from("<I", d, off + 2)[0]
        imm = struct.unpack_from("<I", d, off + 6)[0]
        writes[dst] = imm

    rows = []
    for slot, imm in sorted(writes.items()):
        name = cstr(imm)
        if not name or not name.startswith(PREFIXES):
            continue
        handler = writes.get(slot + 4)
        if handler is None:
            continue
        rows.append((name, imm, slot, slot + 4, handler))

    lines = [
        "// Generated by tools/gen_callbacks.py - do not edit by hand.",
        "//",
        "// Every ActionScript -> C++ callback the F.E.A.R. 2 menu registers. The game",
        "// fills a table of 12-byte {name, handler, flag} rows; these are the slot",
        "// addresses of each row's name and handler, as RVAs against gameclient.dll's",
        "// preferred base of 0x10000000.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace f2au {",
        "",
        "struct MenuCallback {",
        "  const char* name;",
        "  uint32_t name_str;      // RVA of the name string",
        "  uint32_t name_slot;     // RVA of the table row's name pointer",
        "  uint32_t handler_slot;  // RVA of the table row's handler pointer",
        "  uint32_t handler;       // RVA of the handler it is registered with",
        "};",
        "",
        f"inline constexpr int kMenuCallbackCount = {len(rows)};",
        "",
        "inline constexpr MenuCallback kMenuCallbacks[kMenuCallbackCount] = {",
    ]
    for name, s, ns, hs, h in rows:
        lines.append(f'    {{"{name}", 0x{s - IMAGE_BASE:06X}u, 0x{ns - IMAGE_BASE:06X}u, '
                     f"0x{hs - IMAGE_BASE:06X}u, 0x{h - IMAGE_BASE:06X}u}},")
    lines += ["};", "", "}  // namespace f2au", ""]
    with open(args.out, "w") as fh:
        fh.write("\n".join(lines))
    print(f">> wrote {args.out} ({len(rows)} callbacks)")


if __name__ == "__main__":
    main()
