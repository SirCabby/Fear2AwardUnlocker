#!/usr/bin/env python3
"""Generate src/awards_table.h from the game's own database.

Every award has a persisted boolean in the player profile. `IsAchievementComplete`
(gameclient.dll RVA 0x16D7B0) reads it and `GrantAchievement` (0x16D6D0) writes it;
both identify the record as `Storage` link 0 of the award, and both reach the
profile through a key built as

    crc32("Achievements" + <name of the Storage record>)

("Achievements" is the literal prefix at gameclient.dll RVA 0x1F4BB0, pasted in
front of the record name by the helper at 0x82290.) The counter/threshold pair is
what makes the game *grant* an award during play; it is not what the Awards screen
reads back, so the mod writes the boolean.

    Interface/Achievements[i]
        slot 0  RankedOnlyAchievement (bool)
        slot 1  AchievementIndex      (int)
        slot 2  AchievementPoints     (int)
        slot 3  display order         (int)
        slot 4  description loc key   (string)
        slot 5  name loc key          (string)
        slot 6  -> _Structures 'Conditions' record
        slot 8  -> Interface/Collectables 'PCACH_*' / 'PC_DLC_ACH_*'  (Storage)

    Conditions
        value 0  threshold
        value 2  -> Interface/GameProfileData record (the counter), or null

All 58 awards have a Storage record, the nine Reborn DLC ones included - they only
lack the *counter* that would earn them, which is why the game never grants them
on PC, not because it has nowhere to keep them.

Usage:  python3 tools/gen_awards.py --game-dir <FEAR2 dir> [--out src/awards_table.h]
        python3 tools/gen_awards.py --gamedb <file> --print
"""

import argparse
import os
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import gadb  # noqa: E402
import ltar  # noqa: E402

ARCHIVE = "Layer01_v103.Arch01"  # last entry in default.archcfg, so it wins
MEMBER = "database\\Loki.gamedb"

S_RANKED, S_INDEX, S_POINTS, S_ORDER, S_DESC, S_NAME, S_COND, _S7, S_STORAGE = range(9)
KEY_PREFIX = "Achievements"  # gameclient.dll RVA 0x1F4BB0
C_THRESHOLD, _C1, C_COUNTER = range(3)


def load_gamedb(game_dir=None, gamedb=None):
    if gamedb:
        with open(gamedb, "rb") as fh:
            return fh.read()
    archive = os.path.join(game_dir, ARCHIVE)
    if not os.path.isfile(archive):
        sys.exit(f"error: {archive} not found - is --game-dir the F.E.A.R. 2 folder?")
    a = ltar.Archive(archive)
    try:
        return a.read(MEMBER)
    finally:
        a.close()


def collect(db):
    cat = db.category("Interface/Achievements")
    out = []
    for rec in cat.records:
        v = rec.values

        counter, threshold = None, 0
        cond = db.deref(v[S_COND])
        if cond:
            _c, crec = cond
            threshold = crec.values[C_THRESHOLD]
            target = db.deref(crec.values[C_COUNTER])
            if target:
                counter = target[1].name

        storage = db.deref(v[S_STORAGE])
        if not storage:
            sys.exit(f"error: {rec.name} has no Storage record - the award cannot be persisted")
        out.append(
            {
                "id": rec.name,
                "storage": storage[1].name,
                "name_key": db.string(v[S_NAME]),
                "desc_key": db.string(v[S_DESC]),
                "ranked": v[S_RANKED],
                "index": v[S_INDEX],
                "points": v[S_POINTS],
                "order": v[S_ORDER],
                "counter": counter,
                "threshold": threshold,
            }
        )
    # NOTE: the order of this list is load-bearing. The runtime hook identifies an
    # award by its position in Interface/Achievements (it is handed a pointer into
    # a contiguous record array), so kAwards[] MUST stay in raw database order.
    # `order` carries the game's display ordering for the UI to sort by.
    return out


def crc32(name):
    return zlib.crc32(name.encode("latin-1")) & 0xFFFFFFFF


def emit(awards, path):
    lines = [
        "// Generated by tools/gen_awards.py - do not edit by hand.",
        "//",
        "// One row per F.E.A.R. 2 award, read straight out of the game's own",
        "// Database\\Loki.gamedb.",
        "//",
        "// `storage` is the award's own record - the game keeps one byte per award in",
        "// the profile under crc32(\"Achievements\" + storage), which is `storage_crc`.",
        "// That byte is what IsAchievementComplete reads and GrantAchievement writes,",
        "// so it is what the mod writes: every award persists, DLC ones included.",
        "//",
        "// `counter` is the Interface/GameProfileData counter whose reaching `threshold`",
        "// makes the game grant the award during play. It is informational here; the",
        "// nine Reborn DLC awards have none (nullptr), which is why the game never",
        "// grants them on PC.",
        "//",
        "// ORDER IS LOAD-BEARING: rows are in raw Interface/Achievements database",
        "// order, because the hook identifies an award by its index in that table.",
        "// Sort by `order` for display; never reorder this array.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace f2au {",
        "",
        "struct AwardDef {",
        "  const char* id;           // ACH_* record name",
        "  const char* storage;      // PCACH_* / PC_DLC_ACH_* record (also the platform id)",
        "  const char* name_key;     // loc key, Loki.strdb",
        "  const char* desc_key;     // loc key, Loki.strdb",
        "  const char* counter;      // GameProfileData counter, or nullptr",
        "  uint32_t    storage_crc;  // crc32(\"Achievements\" + storage), the .gps key",
        "  uint32_t    counter_crc;  // crc32(counter), or 0",
        "  int32_t     threshold;    // counter >= threshold  =>  the game grants it",
        "  int32_t     points;",
        "  int32_t     index;        // AchievementIndex",
        "  int32_t     order;        // the game's display ordering (1..58)",
        "  bool        ranked_only;  // ranked multiplayer award",
        "};",
        "",
        f"inline constexpr int kAwardCount = {len(awards)};",
        "",
        "inline constexpr AwardDef kAwards[kAwardCount] = {",
    ]
    for a in awards:
        c = f'"{a["counter"]}"' if a["counter"] else "nullptr"
        crc = f"0x{crc32(a['counter']):08X}u" if a["counter"] else "0u"
        skey = f"0x{crc32(KEY_PREFIX + a['storage']):08X}u"
        lines.append(
            f'    {{"{a["id"]}", "{a["storage"]}", "{a["name_key"]}", "{a["desc_key"]}", '
            f'{c}, {skey}, {crc}, {a["threshold"]}, {a["points"]}, {a["index"]}, '
            f'{a["order"]}, {"true" if a["ranked"] else "false"}}},'
        )
    lines += ["};", "", "}  // namespace f2au", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--game-dir")
    ap.add_argument("--gamedb")
    ap.add_argument("--out", default="src/awards_table.h")
    ap.add_argument("--print", dest="show", action="store_true")
    args = ap.parse_args()
    if not args.game_dir and not args.gamedb:
        ap.error("need --game-dir or --gamedb")

    db = gadb.Database(load_gamedb(args.game_dir, args.gamedb))
    awards = collect(db)

    if args.show:
        print(f"{'award':<28}{'storage':<28}{'key':>10}  {'counter':<30}{'thr':>5}{'pts':>5}")
        for a in awards:
            print(
                f"{a['id']:<28}{a['storage']:<28}"
                f"0x{crc32(KEY_PREFIX + a['storage']):08X}  {(a['counter'] or '-'):<30}"
                f"{a['threshold']:>5}{a['points']:>5}"
            )
        n = sum(1 for a in awards if not a["counter"])
        print(f"\n{len(awards)} awards, all persisted; {n} with no counter to earn them")
        return

    emit(awards, args.out)
    print(f">> wrote {args.out} ({len(awards)} awards)")


if __name__ == "__main__":
    main()
